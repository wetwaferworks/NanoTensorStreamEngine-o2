"""Generate engine_gui_cuda.c from littlenemo/src/engine_gui.c (unchanged). The build writes the result to accel/engine_gui_cuda.c.

Adds to the same protocol:
  lane calibration at startup (accel/nemo_calib: CUDA, OpenCL-NV,
  OpenCL-iGPU, CPU probed, verified, benched, cached; fastest correct
  lane wins, CUDA preferred, CPU only if no GPU lane passes)
    --accel auto|cuda|cpu   override the calibrated choice
    --recalibrate           ignore the cache and re-run the tests
    --cuda-pack PACK.nq2    the NTSE pack the CUDA lane runs from
  DTC on by default with predicted expansion (accel/nemo_predict)
    --expand auto|never|always
    --full-path fast|exact  FULL projections: fast (default) or exact order
    --dtc-margin X --dtc-entropy X --dtc-prompt-tokens N
    --dtc-complexity N --dtc-longform 0|1 --dtc-trace --log FILE
READY/HW/STATS/STAT say which lane runs and why the others were
rejected; every step emits a DTC or EXPAND line."""
import sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf-8").read()


def rep(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, (old[:60], n)
    s = s.replace(old, new)


hdr = r"""/* engine_gui_cuda.c - GENERATED by accel/mk_engine_gui_cuda.py from
 * engine_gui.c (which is unchanged). Same protocol, plus lane
 * calibration (accel/nemo_calib), the CUDA lane (accel/nemo_gpu) and
 * DTC-by-default with predicted EXPAND (accel/nemo_predict).
 * Pure C, no mutexes. --host-threads N runs the per-step host work
 * (logit confidence) on N lanes of the zero-mutex nemo_pool. */
"""
s = hdr + s

BRIDGE = r"""#include "tokenizer.h"
#include "nemo_gpu.h"
#include "nemo_calib.h"
#include "nemo_predict.h"

/* ---- GPU bridge, lane calibration, DTC/EXPAND prediction (generated) ---- */
static nemo_gpu *g_gpu = NULL;
static const char *g_lane = "cpu";
static nemo_predict_cfg g_pred;
static int g_turn_full = 0;           /* this turn runs at full precision */
static int g_per_step = 0;            /* a step can be snapshotted and redone */
static int g_n_dtc = 0, g_n_exp = 0;  /* steps this turn */
static long g_s_dtc = 0, g_s_exp = 0; /* steps this session */
static int g_step_no = 0;
static int g_last_tok = -1;
static int g_trace = 0;               /* --dtc-trace: every step's confidence on stderr */
static nemo_pool g_hpool;             /* host lanes for per-step work (zero-mutex pool) */
static int g_host_threads = 1, g_hpool_ok = 0;
static void pct(const char *in, char *out, size_t ol) {
    static const char hx[] = "0123456789ABCDEF";
    size_t j = 0;
    for (; *in && j + 4 < ol; in++) {
        unsigned char ch = (unsigned char)*in;
        if (ch <= 32 || ch == '%' || ch == '=' || ch >= 127) {
            out[j++] = '%'; out[j++] = hx[ch >> 4]; out[j++] = hx[ch & 15];
        } else out[j++] = (char)ch;
    }
    out[j] = 0;
}
static void emit_step(int expanded, const char *what, const char *reason) {
    char r[300];
    pct(reason, r, sizeof r);
    if (expanded) {
        g_n_exp++; g_s_exp++;
        printf("EXPAND tensor=%s tok=%d lane=cuda mode=full reason=%s\n", what, g_step_no, r);
        fprintf(stderr, "predict: EXPAND %s tok=%d reason=%s\n", what, g_step_no, reason);
    } else {
        g_n_dtc++; g_s_dtc++;
        printf("DTC tensor=%s tok=%d lane=cuda mode=dtc reason=%s\n", what, g_step_no, r);
        if (g_trace) fprintf(stderr, "predict: DTC %s tok=%d %s\n", what, g_step_no, reason);
    }
}
/* One DTC step whose logits are checked; below the confidence threshold
 * the state goes back to the snapshot and the step reruns at FULL. */
static int checked_step(int tok, float *logits, const char *what) {
    if (g_turn_full) {
        nemo_gpu_set_full(g_gpu, 1);
        int rc = nemo_gpu_step(g_gpu, tok, logits);
        emit_step(1, what, "turn-expanded");
        return rc;
    }
    nemo_gpu_set_full(g_gpu, 0);
    int snap = g_per_step && g_pred.mode != 1 && nemo_gpu_snapshot(g_gpu) == 0;
    if (nemo_gpu_step(g_gpu, tok, logits) != 0) return -1;
    nemo_confidence k;
    nemo_confidence_of_pool(logits, NEMO_VOCAB, &k, g_hpool_ok ? &g_hpool : NULL);
    char why[200];
    int ex = nemo_predict_step(&g_pred, &k, why, sizeof why);
    if (ex && snap) {
        if (nemo_gpu_restore(g_gpu) != 0) return -1;
        nemo_gpu_set_full(g_gpu, 1);
        int rc = nemo_gpu_step(g_gpu, tok, logits);
        nemo_gpu_set_full(g_gpu, 0);
        if (rc != 0) return -1;
        nemo_confidence k2;
        nemo_confidence_of_pool(logits, NEMO_VOCAB, &k2, g_hpool_ok ? &g_hpool : NULL);
        char why2[300];
        snprintf(why2, sizeof why2, "%s; full: top1 %s (margin=%.3f)", why,
                 k2.top1 == k.top1 ? "same" : "changed", k2.margin);
        emit_step(1, what, why2);
    } else {
        if (ex) snprintf(why + strlen(why), sizeof why - strlen(why), " (no snapshot room: kept DTC)");
        emit_step(0, what, why);
    }
    return 0;
}
static int flush_pending(void) {
    if (g_last_tok < 0) return 0;
    int t = g_last_tok; g_last_tok = -1;
    nemo_gpu_set_full(g_gpu, g_turn_full);
    return nemo_gpu_step(g_gpu, t, NULL);
}
static int gpu_prefill(nemo_model *m, const int *ids, int n, float *hidden) {
    if (!g_gpu) return nemo_model_prefill(m, ids, n, hidden);
    (void)hidden;
    if (n < 1 || m->n_pos + n > m->max_pos) return -1;
    if (flush_pending() != 0) { m->state_valid = 0; return -1; }
    nemo_gpu_set_full(g_gpu, g_turn_full);
    /* batched prefill: bit-identical to stepping the tokens one by one */
    if (n > 1 && nemo_gpu_prefill(g_gpu, ids, n - 1) != 0) { m->state_valid = 0; return -1; }
    if (n > 1) {
        printf("%s tensor=prefill tok=0 lane=cuda mode=%s reason=prompt%%20tokens%%3D%d\n",
               g_turn_full ? "EXPAND" : "DTC", g_turn_full ? "full" : "dtc", n - 1);
        if (g_turn_full) { g_n_exp++; g_s_exp++; } else { g_n_dtc++; g_s_dtc++; }
    }
    /* The chunk's last token stays pending: gpu_head steps it with its
     * logits checked, or the next chunk / step flushes it first. */
    g_last_tok = ids[n - 1];
    m->n_pos += n;
    return 0;
}
static int gpu_head(nemo_model *m, const float *hidden, float *logits) {
    if (!g_gpu) return nemo_model_head(m, hidden, logits);
    (void)hidden;
    if (g_last_tok < 0) return nemo_gpu_logits(g_gpu, logits) == 0 ? 0 : -1;
    int t = g_last_tok; g_last_tok = -1;
    g_step_no = 0;
    return checked_step(t, logits, "prompt-last") == 0 ? 0 : -1;
}
static int gpu_step(nemo_model *m, int tok, float *logits) {
    if (!g_gpu) return nemo_model_step(m, tok, logits);
    if (!m->state_valid) return -2;
    if (m->n_pos >= m->max_pos) return -1;
    if (flush_pending() != 0) { m->state_valid = 0; return -1; }
    g_step_no++;
    if (checked_step(tok, logits, "step") != 0) { m->state_valid = 0; return -1; }
    m->n_pos++;
    return 0;
}
static int gpu_step_hidden(nemo_model *m, int tok, float *hidden) {
    if (!g_gpu) return nemo_model_step_hidden(m, tok, hidden);
    (void)hidden;
    if (!m->state_valid) return -2;
    if (m->n_pos >= m->max_pos) return -1;
    if (flush_pending() != 0) { m->state_valid = 0; return -1; }
    nemo_gpu_set_full(g_gpu, g_turn_full);
    if (nemo_gpu_step(g_gpu, tok, NULL) != 0) { m->state_valid = 0; return -1; }
    m->n_pos++;
    return 0;
}
static void gpu_reset(nemo_model *m) {
    nemo_model_reset(m);
    g_last_tok = -1;
    if (g_gpu) nemo_gpu_reset(g_gpu);
}
/* Turn-level prediction from the user's text (before any compute). */
static void predict_turn(nemo_tokenizer *tk, const char *text) {
    g_n_dtc = g_n_exp = 0; g_step_no = 0; g_turn_full = 0;
    if (!g_gpu) return;
    static int ids[8192];
    int n = nemo_tokenizer_encode(tk, text, ids, 8192);
    int think = strstr(text, "/think") != NULL;
    char why[240], e2[600];
    g_turn_full = nemo_predict_turn(&g_pred, text, n < 0 ? 0 : n, think, why, sizeof why);
    if (g_turn_full && !nemo_gpu_full_available(g_gpu, NULL, NULL, 0)) {
        snprintf(why + strlen(why), sizeof why - strlen(why), " (FULL unavailable: stays DTC)");
        g_turn_full = 0;
    }
    pct(why, e2, sizeof e2);
    printf("STAT turn_lane=%s turn_reason=%s\n", g_turn_full ? "expand" : "dtc", e2);
    fprintf(stderr, "predict: turn %s reason=%s\n", g_turn_full ? "EXPAND" : "DTC", why);
}
"""
rep('#include "tokenizer.h"\n', BRIDGE)
rep('    nemo_model_reset(e->model);', '    gpu_reset(e->model);')
rep('nemo_model_prefill(e->model,', 'gpu_prefill(e->model,')
rep('nemo_model_head(e->model,', 'gpu_head(e->model,')
rep('nemo_model_step(e->model,', 'gpu_step(e->model,')
rep('nemo_model_step_hidden(e->model,', 'gpu_step_hidden(e->model,')
rep('static void run_turn(engine *e, const char *user_text) {\n    if (!e->chat) {',
    'static void run_turn(engine *e, const char *user_text) {\n    predict_turn(e->tk, user_text);\n    if (!e->chat) {')
rep('                         "stopped=%d lane=cpu",',
    '                         "stopped=%d lane=%s dtc_steps=%d expand_steps=%d",')
rep('                         stopped);', '                         stopped, g_lane, g_n_dtc, g_n_exp);')
rep(r'    printf("MEM peak_mb=%.1f\n", peak_kb() / 1024.0);', r'''    printf("MEM peak_mb=%.1f\n", peak_kb() / 1024.0);
    if (g_gpu)
        printf("STAT dtc_steps=%d expand_steps=%d dtc_session=%ld expand_session=%ld\n",
               g_n_dtc, g_n_exp, g_s_dtc, g_s_exp);''')
rep('    int chat = 0, think_default = 0;', r'''    int chat = 0, think_default = 0;
    const char *cuda_pack = NULL, *accel_override = "auto";
    int recal = 0;
    nemo_predict_defaults(&g_pred);''')
rep('        else if (i + 1 < argc && !strcmp(argv[i], "--threads"))', r'''        else if (i + 1 < argc && !strcmp(argv[i], "--cuda-pack"))
            cuda_pack = argv[++i];
        else if (i + 1 < argc && !strcmp(argv[i], "--accel")) {
            accel_override = argv[++i];
            if (strcmp(accel_override, "auto") && strcmp(accel_override, "cuda") && strcmp(accel_override, "cpu")) {
                fprintf(stderr, "nemo-engine: --accel auto|cuda|cpu\n");
                return 2;
            }
        }
        else if (!strcmp(argv[i], "--recalibrate")) recal = 1;
        else if (i + 1 < argc && !strcmp(argv[i], "--log")) {
            /* stderr (calibration verdicts, every DTC/EXPAND decision) to a file:
             * a windowless launch from the GUI has no console to show it. */
            const char *lp = argv[++i];
            if (!freopen(lp, "a", stderr)) fprintf(stdout, "STAT log_error=cannot%%20open%%20log\n");
            else setvbuf(stderr, NULL, _IONBF, 0);
        }
        else if (!strcmp(argv[i], "--dtc-trace")) g_trace = 1;
        else if (i + 1 < argc && !strcmp(argv[i], "--host-threads")) {
            g_host_threads = atoi(argv[++i]);
            if (g_host_threads < 1 || g_host_threads > 8) {
                fprintf(stderr, "nemo-engine: --host-threads 1..8\n");
                return 2;
            }
        }
        else if (i + 1 < argc && !strcmp(argv[i], "--full-path")) {
            /* FULL projections: fast (default) or the exact (reference-order) path */
            const char *fp = argv[++i];
            if (strcmp(fp, "fast") && strcmp(fp, "exact")) { fprintf(stderr, "nemo-engine: --full-path fast|exact\n"); return 2; }
#ifdef _WIN32
            _putenv(!strcmp(fp, "exact") ? "NEMO_GPU_GEMV_FULL=exact" : "NEMO_GPU_GEMV_FULL=f");
#else
            setenv("NEMO_GPU_GEMV_FULL", !strcmp(fp, "exact") ? "exact" : "f", 1);
#endif
        }
        else if (i + 1 < argc && !strcmp(argv[i], "--expand")) {
            const char *x = argv[++i];
            g_pred.mode = !strcmp(x, "never") ? 1 : !strcmp(x, "always") ? 2 : 0;
        }
        else if (i + 1 < argc && !strcmp(argv[i], "--dtc-margin")) g_pred.margin = atof(argv[++i]);
        else if (i + 1 < argc && !strcmp(argv[i], "--dtc-entropy")) g_pred.entropy = atof(argv[++i]);
        else if (i + 1 < argc && !strcmp(argv[i], "--dtc-prompt-tokens")) g_pred.prompt_tokens = atoi(argv[++i]);
        else if (i + 1 < argc && !strcmp(argv[i], "--dtc-complexity")) g_pred.complex_score = atoi(argv[++i]);
        else if (i + 1 < argc && !strcmp(argv[i], "--dtc-longform")) g_pred.longform = atoi(argv[++i]);
        else if (i + 1 < argc && !strcmp(argv[i], "--threads"))''')
rep('    if (nthreads < 1) nthreads = 1;', r'''    if (nthreads < 1) nthreads = 1;
    /* Lane calibration: probe, verify, bench, cache; then open the lane. */
    nemo_calib cal;
    char lane_why[400] = "";
    nemo_calib_run(&cal, accel_override, recal, cuda_pack != NULL);
    nemo_calib_log(&cal);
    if (!strcmp(cal.lane, "cuda")) {
        if (!cuda_pack) {
            snprintf(lane_why, sizeof lane_why, "no --cuda-pack given");
        } else if (nemo_gpu_open(&g_gpu, argv[1], cuda_pack, layers, max_pos, lane_why, sizeof lane_why) != 0) {
            g_gpu = NULL;
        }
        if (!g_gpu) {
            fprintf(stderr, "nemo-engine: CUDA lane unavailable: %s\n", lane_why);
            if (!strcmp(accel_override, "cuda")) {
                printf("ERROR CUDA lane unavailable: %s\n", lane_why);
                fflush(stdout);
                return 1;
            }
            fprintf(stderr, "nemo-engine: falling back to the CPU lane for this launch\n");
        }
    }
    if (g_gpu) {
        g_lane = "cuda";
        nthreads = 1; /* the CPU model only keeps books */
        nemo_gpu_full_available(g_gpu, &g_per_step, NULL, 0);
        if (g_pred.mode == 2) g_per_step = 0;
        memset(&g_hpool, 0, sizeof g_hpool);
        if (g_host_threads > 1) g_hpool_ok = nemo_pool_init(&g_hpool, g_host_threads) == 0;
    }''')
rep(r'''    printf("READY nemo-engine 3 model=Nemotron-Nano-9B-v2 weights=raw "
           "layers=%d cores=%d threads=%d mode=%s simd=%d accel=cpu "
           "chat=%d think=%d\n",
           model.layer_limit, cores, model.nthreads,
           threads > 0 ? "custom" : mode, nemo_simd_active(),
           chat, think_default);
    printf("HW cores=%d threads=%d accel=cpu\n", cores, model.nthreads);''', r'''    nemo_gpu_info ginf;
    memset(&ginf, 0, sizeof ginf);
    char fullwhy[200] = "";
    if (g_gpu) {
        nemo_gpu_info_get(g_gpu, &ginf);
        nemo_gpu_full_available(g_gpu, NULL, fullwhy, sizeof fullwhy);
        e.bytes_tok = ginf.bytes_per_token;
        e.head_bytes = ginf.head_bytes;
        fprintf(stderr,
                "nemo-engine: CUDA lane on %s sm_%d%d, %.0f MiB resident "
                "(lm_head %s), %.0f MiB free at open; DTC on, EXPAND %s (%s)\n",
                ginf.device, ginf.cc_major, ginf.cc_minor,
                ginf.vram_used_by_us / 1048576.0,
                ginf.head_int8 ? "int8 per-row" : "bf16",
                ginf.vram_free_at_open / 1048576.0,
                !ginf.full_ok ? "off" : ginf.snap_ok ? "turn+step" : "turn only", fullwhy);
    }
    printf("READY nemo-engine 3 model=Nemotron-Nano-9B-v2 weights=%s "
           "layers=%d cores=%d threads=%d mode=%s simd=%d accel=%s "
           "chat=%d think=%d\n",
           g_gpu ? "nq2-pq4" : "raw",
           model.layer_limit, cores, model.nthreads,
           threads > 0 ? "custom" : mode, nemo_simd_active(), g_lane,
           chat, think_default);
    {
        static char gd[300], cw[800], ow[800], iw[800], pw[800], lw[1000];
        snprintf(gd, sizeof gd, "none");
        if (g_gpu) pct(ginf.device, gd, sizeof gd);
        else if (cal.probe.device[0]) pct(cal.probe.device, gd, sizeof gd);
        pct(cal.cuda_why, cw, sizeof cw); pct(cal.oclnv_why, ow, sizeof ow);
        pct(cal.igpu_why, iw, sizeof iw); pct(cal.cpu_why, pw, sizeof pw);
        pct(lane_why[0] ? lane_why : "-", lw, sizeof lw);
        printf("HW cores=%d threads=%d accel=%s gpu=%s calib=%s dtc=%s expand=%s host_threads=%d prefill_chunk=%d full_path=%s\n", cores, model.nthreads, g_lane, gd,
               cal.cached ? "cached" : "fresh", g_gpu ? "on" : "off",
               !g_gpu ? "off" : g_pred.mode == 1 ? "never" : g_pred.mode == 2 ? "always"
               : !ginf.full_ok ? "off" : ginf.snap_ok ? "auto" : "turn",
               g_hpool_ok ? g_host_threads : 1, g_gpu ? nemo_gpu_prefill_chunk(g_gpu) : 0,
               !g_gpu ? "off" : nemo_gpu_full_fast(g_gpu) ? "fast" : "exact");
        printf("STAT calib=%s calib_ms=%.0f lane=%s lane_cuda=%s lane_opencl_nv=%s lane_opencl_igpu=%s lane_cpu=%s "
               "est_cuda_tps=%.2f est_cpu_tps=%.3f open_note=%s\n",
               cal.cached ? "cached" : "fresh", cal.ms, g_lane, cal.cuda_status, cal.oclnv_status, cal.igpu_status,
               cal.cpu_status, cal.est_cuda_tps, cal.est_cpu_tps, lw);
        printf("STAT cuda_reason=%s opencl_nv_reason=%s opencl_igpu_reason=%s cpu_reason=%s\n", cw, ow, iw, pw);
        if (g_gpu)
            printf("STAT dtc_margin=%.3f dtc_entropy=%.3f dtc_prompt_tokens=%d dtc_complexity=%d\n",
                   g_pred.margin, g_pred.entropy, g_pred.prompt_tokens, g_pred.complex_score);
    }''')
